import 'package:paint_bridge/paint_bridge.dart';

/// The tool bar's settings are the core's plain record; the bar changes
/// one field at a time.
extension ToolSettingsCopy on ToolSettings {
  ToolSettings copyWith({
    double? width,
    bool? antialias,
    bool? alphaBlending,
    double? hardness,
    double? tolerance,
    FloodMode? floodMode,
    CombineMode? selectionMode,
    SelectDraw? selectDraw,
    (double, double)? fixed,
    Resampling? resampling,
    GradientKind? gradient,
    bool? gradientTransparency,
    ShapeDraw? shapeDraw,
    PickerAfter? pickerAfter,
    LineCap? lineStart,
    LineCap? lineEnd,
    DashStyle? dash,
    String? font,
    double? fontSize,
    bool? bold,
    bool? italic,
    bool? underline,
    bool? strikeout,
    PaintTextAlign? textAlign,
  }) => ToolSettings(
    width: width ?? this.width,
    antialias: antialias ?? this.antialias,
    alphaBlending: alphaBlending ?? this.alphaBlending,
    hardness: hardness ?? this.hardness,
    tolerance: tolerance ?? this.tolerance,
    floodMode: floodMode ?? this.floodMode,
    selectionMode: selectionMode ?? this.selectionMode,
    selectDraw: selectDraw ?? this.selectDraw,
    fixed: fixed ?? this.fixed,
    resampling: resampling ?? this.resampling,
    gradient: gradient ?? this.gradient,
    gradientTransparency: gradientTransparency ?? this.gradientTransparency,
    shapeDraw: shapeDraw ?? this.shapeDraw,
    pickerAfter: pickerAfter ?? this.pickerAfter,
    lineStart: lineStart ?? this.lineStart,
    lineEnd: lineEnd ?? this.lineEnd,
    dash: dash ?? this.dash,
    font: font ?? this.font,
    fontSize: fontSize ?? this.fontSize,
    bold: bold ?? this.bold,
    italic: italic ?? this.italic,
    underline: underline ?? this.underline,
    strikeout: strikeout ?? this.strikeout,
    textAlign: textAlign ?? this.textAlign,
  );
}
